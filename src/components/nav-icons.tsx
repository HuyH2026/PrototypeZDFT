// Glyph target size within the icon's 20-unit slot. The Figma nav icons sit
// inset within their box (~16 of 20 units) rather than filling it edge-to-edge,
// which keeps the rail feeling light. NavGlyph centers each glyph and scales its
// longest dimension to this target, so every icon shares one visual weight
// regardless of its source viewBox — and callers just pass the design `size`.
const GLYPH_TARGET = 16
const SLOT = 20

// Wraps a raw glyph (authored in its own `viewW`×`viewH` coordinate space) in a
// square 20×20 viewBox, centered and inset to GLYPH_TARGET.
function NavGlyph({
  size = 20,
  className,
  viewW,
  viewH,
  children,
}: NavIconProps & { viewW: number; viewH: number; children: ReactNode }) {
  const scale = GLYPH_TARGET / Math.max(viewW, viewH)
  const tx = (SLOT - viewW * scale) / 2
  const ty = (SLOT - viewH * scale) / 2
  return (
    <svg width={size} height={size} viewBox={`0 0 ${SLOT} ${SLOT}`} fill="none" className={className}>
      <g transform={`translate(${tx} ${ty}) scale(${scale})`}>{children}</g>
    </svg>
  )
}

